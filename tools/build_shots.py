"""
Generate css/service-shots.css from whatever is actually in assets/services/.

Declaring the nine background-images unconditionally made the browser request
each missing file repeatedly (once per repaint), producing a stream of 404s.
Emitting a rule only when the file exists means a missing image costs nothing
at all -- no request, no console noise -- and the card simply keeps its icon.

Run:  python tools/build_shots.py   (also run by tools/build_dist.py)
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "services"
OUT = ROOT / "css" / "service-shots.css"

SLUGS = [
    "media-buying",
    "web-development",
    "brand-identity",
    "competitor-market-analysis",
    "photography-reels",
]

lines = [
    "/* GENERATED by tools/build_shots.py - do not edit by hand.",
    "   A rule appears here only when the matching image exists, so missing",
    "   photography costs no requests. Add files to assets/services/ and",
    "   re-run the script.",
    "",
    "   Each rule is gated behind .stage-services.live so the browser does not",
    "   fetch the photographs until the Services stage first comes on screen.",
    "   They are hover art for one section; downloading them during the initial",
    "   page load would cost every visitor a third of a megabyte for something",
    "   most of them have not scrolled to yet. */",
]
found = 0
for slug in SLUGS:
    for ext in ("jpg", "jpeg", "png", "webp"):
        f = SRC / f"{slug}.{ext}"
        if f.exists():
            lines.append(
                f'.stage-services.live .scard[href*="{slug}"]'
                f'{{--shot:url(../assets/services/{f.name});}}'
            )
            found += 1
            break

OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"service-shots.css: {found} of {len(SLUGS)} images present")
