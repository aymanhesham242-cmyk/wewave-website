"""
Assemble dist/ — the folder that gets deployed to Cloudflare Pages.

Deploys the 3-file source (not the single-file build): on a real host the
relative assets resolve normally, so there's no reason to inline 3MB of
base64. The profile button falls back to its plain link, which works here.

Configured to be shareable but not indexed: robots.txt disallows everything
and _headers sends X-Robots-Tag: noindex.

Run:  python tools/build_dist.py
"""
import pathlib
import re
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIST = ROOT / "dist"

# =========================================================================
# THE LAUNCH SWITCH
#
# Leave this empty and the build behaves exactly as it always has: no
# canonical URL, no social cards, no sitemap, robots.txt disallowing
# everything and X-Robots-Tag: noindex on every response. That is the right
# state for a site that is not announced yet, and it is the current state.
#
# Put the real public origin here -- no trailing slash, e.g.
# "https://wewave.example.com" -- and the same build emits canonical and
# Open Graph tags, writes a sitemap, and opens the site to search engines.
#
# Nothing else needs editing. Do not set it to the workers.dev address unless
# that really is the address the business will publish: a canonical URL is a
# promise about where a page permanently lives, and moving it afterwards
# costs more than leaving it unset.
# =========================================================================
SITE_URL = ""

# Pages that belong in a sitemap: the homepage and every service page.
# /admin is deliberately absent and always will be.
PUBLIC_PAGES = ["/"] + [
    "/services/" + p.stem for p in sorted((ROOT / "services").glob("*.html"))
] if (ROOT / "services").exists() else ["/"]


def head_tags(page_path: str, html: str) -> str:
    """Canonical + social tags for one page, built from what the page says.

    Title and description are read out of the page itself rather than
    invented here, so the card can never disagree with the page.
    """
    if not SITE_URL:
        return ""
    m = re.search(r"<title>(.*?)</title>", html, re.S)
    title = re.sub(r"\s+", " ", m.group(1)).strip() if m else "WeWave"
    m = re.search(r'<meta name="description" content="(.*?)"', html, re.S)
    desc = re.sub(r"\s+", " ", m.group(1)).strip() if m else ""
    url = SITE_URL + ("" if page_path == "/" else page_path)
    img = SITE_URL + "/assets/wewave-mark.png"
    return (
        f'\n<link rel="canonical" href="{url}">'
        f'\n<meta property="og:type" content="website">'
        f'\n<meta property="og:site_name" content="WeWave">'
        f'\n<meta property="og:url" content="{url}">'
        f'\n<meta property="og:title" content="{title}">'
        + (f'\n<meta property="og:description" content="{desc}">' if desc else "")
        + f'\n<meta property="og:image" content="{img}">'
        f'\n<meta name="twitter:card" content="summary">'
        f'\n<meta name="twitter:title" content="{title}">'
        + (f'\n<meta name="twitter:description" content="{desc}">' if desc else "")
        + f'\n<meta name="twitter:image" content="{img}">\n'
    )


def with_head_tags(page_path: str, html: str) -> str:
    extra = head_tags(page_path, html)
    return html.replace("</head>", extra + "</head>", 1) if extra else html

# Empty dist/ rather than removing it: on Windows the directory handle is
# often held by an editor, a file browser or a static server, which makes
# rmtree fail on the folder itself even after its contents are gone.
DIST.mkdir(exist_ok=True)
for item in DIST.iterdir():
    if item.is_dir():
        shutil.rmtree(item)
    else:
        item.unlink()

# --- pages ---------------------------------------------------------------
html = (ROOT / "index.html").read_text(encoding="utf-8")
# ship the web-weight profile (2.1MB) rather than the 6.4MB original
html = html.replace("assets/wewave-profile.pdf", "assets/wewave-profile-web.pdf")
(DIST / "index.html").write_text(with_head_tags("/", html), encoding="utf-8")

subprocess.run([sys.executable, str(ROOT / "tools" / "build_shots.py")], check=True)

for rel in ("css/style.css", "css/service-shots.css", "css/service.css", "js/main.js",
            "js/meeting-modal.js", "js/voice.js", "js/contact.js",
            "js/showcase.js", "js/casestudy.js", "js/analytics.js"):
    dest = DIST / rel
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(ROOT / rel, dest)

# one full page per service (generated by tools/build_services.py)
if (ROOT / "services").exists():
    shutil.copytree(ROOT / "services", DIST / "services")
    if SITE_URL:
        for page in sorted((DIST / "services").glob("*.html")):
            body = page.read_text(encoding="utf-8")
            page.write_text(with_head_tags("/services/" + page.stem, body), encoding="utf-8")

# --- assets --------------------------------------------------------------
(DIST / "assets").mkdir()
shutil.copy2(ROOT / "assets/wewave-mark.png", DIST / "assets/wewave-mark.png")
shutil.copy2(
    ROOT / "assets/wewave-profile-web.pdf", DIST / "assets/wewave-profile-web.pdf"
)
shutil.copytree(ROOT / "assets/clients", DIST / "assets/clients")

# voice-note testimonials (two encodings each: opus for most browsers, aac
# for Safari, which cannot play Ogg)
voices = ROOT / "assets/voices"
if voices.exists() and any(voices.iterdir()):
    shutil.copytree(voices, DIST / "assets/voices")

# service hover artwork (css/service-shots.css only references files that
# exist, so a partial folder is fine -- but it must actually ship)
services_art = ROOT / "assets/services"
if services_art.exists():
    shutil.copytree(
        services_art, DIST / "assets/services",
        ignore=shutil.ignore_patterns("README.md"),
    )

# client site screenshots for the work showcase. Real captures of the real
# sites -- see tools/save_folio_shot.py. The panel only requests one when its
# segment is selected, so these cost nothing on page load.
folio = ROOT / "assets/folio"
if folio.exists() and any(folio.iterdir()):
    shutil.copytree(folio, DIST / "assets/folio")

# case-study screenshots (the pages fall back to a labelled slot if absent)
cases = ROOT / "assets/cases"
if cases.exists() and any(cases.iterdir()):
    shutil.copytree(cases, DIST / "assets/cases")

# admin panel (a static shell; it holds no data without a token)
if (ROOT / 'admin').exists():
    shutil.copytree(ROOT / 'admin', DIST / 'admin')

# A future session that edits dist/ directly will see the change go live and
# then lose it on the next build. Say so inside the folder itself.
(DIST / "DO-NOT-EDIT.md").write_text(
    """# Generated folder

Everything here is produced by `python tools/build_dist.py` from the project
root. Cloudflare deploys *this* folder, which is why it is committed -- but it
is output, not source.

Edit the source files (`index.html`, `css/`, `js/`, `services/`), then re-run
the build. Anything changed in here is overwritten without warning.
""",
    encoding="utf-8",
)

# --- search engines -------------------------------------------------------
# Closed until SITE_URL says otherwise. /admin stays disallowed either way
# and is never listed in the sitemap.
if SITE_URL:
    (DIST / "robots.txt").write_text(
        "User-agent: *\n"
        "Disallow: /admin/\n"
        "Allow: /\n\n"
        f"Sitemap: {SITE_URL}/sitemap.xml\n",
        encoding="utf-8",
    )
    urls = "".join(
        f"  <url><loc>{SITE_URL}{'' if u == '/' else u}</loc></url>\n"
        for u in PUBLIC_PAGES
    )
    (DIST / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        f"{urls}</urlset>\n",
        encoding="utf-8",
    )
else:
    (DIST / "robots.txt").write_text(
        "User-agent: *\nDisallow: /\n", encoding="utf-8"
    )
# --- response headers -----------------------------------------------------
# Workers Assets serves `_headers` the way Pages does -- confirmed against the
# live deployment, which already returns the first three.
#
# script-src is 'self' with no 'unsafe-inline': no page carries an inline
# <script> any more (the two admin panels' scripts were moved out to app.js
# files for exactly this reason). style-src has to keep 'unsafe-inline' --
# the stage engine writes inline styles every frame and the dashboards use
# style attributes, so a strict style-src would break the design.
CSP = (
    "default-src 'self'; "
    "script-src 'self'; "
    "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; "
    "font-src 'self' https://fonts.gstatic.com; "
    "img-src 'self' data:; "
    "media-src 'self'; "
    # The work showcase frames clients' own sites. Without this,
    # frame-src falls back to default-src 'self' and every preview is
    # blocked silently. Kept to https so a preview can never be a
    # cleartext page; narrow it to a host list if the roster settles.
    "frame-src https:; "
    "connect-src 'self'; "
    "object-src 'none'; "
    "base-uri 'self'; "
    "form-action 'self'; "
    "frame-ancestors 'none'; "
    "upgrade-insecure-requests"
)

# Only this line of the header block depends on the launch switch.
ROBOTS_LINE = (
    "  X-Robots-Tag: index, follow\n" if SITE_URL
    else "  X-Robots-Tag: noindex, nofollow, noarchive\n"
)

(DIST / "_headers").write_text(
    "/*\n"
    f"{ROBOTS_LINE}"
    "  X-Content-Type-Options: nosniff\n"
    "  Referrer-Policy: strict-origin-when-cross-origin\n"
    f"  Content-Security-Policy: {CSP}\n"
    "  X-Frame-Options: DENY\n"
    "  Strict-Transport-Security: max-age=31536000; includeSubDomains\n"
    "  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()\n"
    "\n"
    # Artwork and media are not content-hashed, so this is the honest trade: a
    # replaced logo reaches everyone within a day, and in exchange a repeat
    # visitor stops re-validating ~20 files one round trip at a time. CSS and
    # JS are left revalidating -- they change on every deploy.
    "/assets/*\n"
    "  Cache-Control: public, max-age=86400, stale-while-revalidate=604800\n"
    "\n"
    "/admin/*\n"
    "  Cache-Control: no-store\n"
    "  X-Robots-Tag: noindex, nofollow, noarchive\n",
    encoding="utf-8",
)

total = sum(f.stat().st_size for f in DIST.rglob("*") if f.is_file())
count = sum(1 for f in DIST.rglob("*") if f.is_file())
print(f"dist/ ready — {count} files, {total/1024/1024:.2f} MB")
for f in sorted(DIST.rglob("*")):
    if f.is_file():
        print(f"  {f.relative_to(DIST).as_posix():42s} {f.stat().st_size/1024:8.1f} KB")
